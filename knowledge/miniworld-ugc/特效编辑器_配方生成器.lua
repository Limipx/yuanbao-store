-------- 配方检索 --------
local function _findR(name)
    if not name or name == "" then return nil end
    for i = 1, #RECIPES do
        if RECIPES[i].n == name then return RECIPES[i] end
    end
    for i = 1, #RECIPES do
        if _has(RECIPES[i].n, name) then return RECIPES[i] end
    end
    local best, bs = nil, 0
    for i = 1, #RECIPES do
        for w in string.gmatch(RECIPES[i].k, "[^|]+") do
            if _has(name, w) and string.len(w) > bs then
                bs, best = string.len(w), RECIPES[i]
            end
        end
    end
    return best
end

