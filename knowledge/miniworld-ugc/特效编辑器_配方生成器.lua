local MAXB = 380

local function _p(text)
    if not text or text == "" then text = "(空)" end
    local buf, n = "", 0
    local function flush()
        if buf ~= "" then
            print(string.sub(buf, 1, string.len(buf) - 1))
            buf, n = "", 0
        end
    end
    for line in string.gmatch(text .. "\n", "(.-)\n") do
        local ln = string.len(line) + 1
        if n + ln > MAXB then flush() end
        buf = buf .. line .. "\n"
        n = n + ln
    end
    flush()
end

local function _has(s, w)
    if not s or not w then return false end
    return string.find(s, w, 1, true) ~= nil
end

