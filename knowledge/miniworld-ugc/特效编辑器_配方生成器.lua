Script["自检"] = function(self)
    local ok, fail = 0, 0
    local function chk(c, m)
        if c then ok = ok + 1 else fail = fail + 1 print("  ✗ " .. m) end
    end
    chk(#RECIPES >= 15, "配方数量 " .. #RECIPES)
    chk(#PARAMS >= 15, "参数数量 " .. #PARAMS)
    chk(#TROUBLE >= 5, "排查数量 " .. #TROUBLE)
    for i = 1, #RECIPES do
        chk(RECIPES[i].n ~= "" and RECIPES[i].b ~= "", "配方" .. i .. "空")
        chk(_findR(RECIPES[i].n) == RECIPES[i], "配方" .. i .. "检索失败")
    end
    for i = 1, #PARAMS do
        chk(PARAMS[i].n ~= "" and PARAMS[i].b ~= "", "参数" .. i .. "空")
        chk(_findP(PARAMS[i].n) ~= nil, "参数" .. i .. "检索失败")
    end
    for i = 1, #TROUBLE do
        chk(_findT(TROUBLE[i].n) ~= nil, "排查" .. i .. "检索失败")
    end
    chk(_has("樱花飘落", "樱花"), "关键词匹配")
    chk(_findR("飘落") ~= nil, "模糊匹配飘落")
    chk(_pick(COLOR, "红色爆炸", COLOR[1]).c == "#FF5A4E", "颜色识别")
    chk(_pick(MOTION, "往上飞", MOTION[5]).g == "-0.4", "运动识别")
    print("[自检] 通过 " .. ok .. " / 失败 " .. fail)
    _p(fail == 0 and "★自检全部通过，可以正常使用" or "★自检有失败项，看上面 ✗ 行")
    return tostring(ok)
end

